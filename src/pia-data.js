/* 입력 봇 결과(업무 목록) → 3개 흐름표 행으로 변환 */
export function tasksToRows(tasks, dept) {
  const coll = [], ret = [], prov = [];
  tasks.forEach((t) => {
    if (!t.업무명) return;
    const d = t.수집담당자 || t.부서 || dept || "";
    coll.push({ 업무명: t.업무명 || "", 동의여부: t.동의여부 || "", 수집근거: t.수집근거 || "", 수집목적: t.수집목적 || "", 수집항목: t.수집항목 || "", 수집경로: t.수집경로 || "", 정보주체유형: t.정보주체유형 || "", 수집대상: t.수집대상 || "", 수집주기: t.수집주기 || "", 수집담당자: d });
    ret.push({ 업무명: t.업무명 || "", 보유형태: t.보유형태 || "", 암호화항목: t.암호화항목 || "", 이용목적: t.이용목적 || "", 이용항목: t.이용항목 || t.수집항목 || "", 개인정보취급자: t.개인정보취급자 || d, 이용방법: t.이용방법 || "" });
    prov.push({ 업무명: t.업무명 || "", 제공목적: t.제공목적 || "", 제공자: t.제공자 || d, 수신자: t.수신자 || "", 제공정보: t.제공정보 || "", 제공방법: t.제공방법 || "", 제공주기: t.제공주기 || "", 암호화여부: t.암호화여부 || "", 제공근거: t.제공근거 || "", 보관기간: t.보관기간 || "", 파기담당자: t.파기담당자 || d, 파기절차: t.파기절차 || "", 분리보관여부: t.분리보관여부 || "" });
  });
  return { coll, ret, prov };
}

